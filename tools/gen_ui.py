def render_tables_py(p, n, i, w):
    machines = {m: dict(sorted(table.items())) for m, table in sorted(p['machines'].items())}
    parts = [PY_HEAD, '"""The TUI\'s copy of the V1 client tables (p17-design-gate A1):\n'
             'navigation, presentation, triggers, invalidation and the relationship words,\n'
             'from the JSON the SPA reads."""\n']
    for name, value in (('DESTINATIONS', n['destinations']),
                        ('CONTROL_SECTIONS', n['control_sections']),
                        ('INSPECTOR_TABS', n['inspector_tabs']), ('TABS', n['tabs']),
                        ('CLASSES', p['classes']), ('PRESENTATION', machines),
                        ('LABELS', _labels(p)), ('TRIGGERS', triggers()), ('RULES', i['rules']),
                        ('EDGE_WORDS', w['words'])):
        parts.append('\n%s = %s\n' % (name, _py(value)))
    return ''.join(parts)


def render_tokens_py(t):
    """Each foreground role as the nearest non-system ANSI-256 colour (design
    system §15: never 0-15, as the legacy themes do)."""
    from claude_sessions.themes import hex_to_x256
    skip = ('bg', 'surface-1', 'surface-2', 'surface-3', 'on-primary')
    colours = {name: {role: hex_to_x256(h) for role, h in theme.items() if role not in skip}
               for name, theme in t['themes'].items()}
    shell = {name: {'bg': theme['bg'], 'attention': theme['state.attention']}
             for name, theme in t['themes'].items()}
    return (PY_HEAD + '"""The token table as ANSI-256 colours per theme (p17-design-gate A7)."""\n'
            + '\nCOLOURS = %s\n' % _py(colours)
            + "\n#: What the desktop shell draws outside the page (p19-design-gate B8): its\n"
              "#: pre-load background and the tray icon's attention dot, per OS scheme.\n"
            + 'SHELL = %s\n' % _py(shell))


def outputs():
    t, p = load(TOKENS), load(PRESENTATION)
    n, i, mo, w = load(NAVIGATION), load(INVALIDATION), load(MOTION), load(EDGES)
    return {CSS_OUT: render_css(t), TOKENS_TS: render_tokens_ts(t),
            PRES_TS: render_presentation_ts(p), NAV_TS: render_nav_ts(n),
            RULES_TS: render_rules_ts(i), TABLES_PY: render_tables_py(p, n, i, w),
            WORDS_PY: render_words_py(p),
            TOKENS_PY: render_tokens_py(t), MOTION_TS: render_motion_ts(mo), EDGES_TS: render_edges_ts(w),
            APPEARANCE_JS: render_appearance_js(t)},         problems(p, t) + token_problems(t) + nav_problems(n) + motion_problems(mo, t)


def main(argv):
    files, bad = outputs()
    if bad:
        print('\n'.join(bad), file=sys.stderr)
        return 1
    stale = []
    for path, text in files.items():
        cur = open(path, encoding='utf-8').read() if os.path.exists(path) else None
        if '--check' in argv:
            if cur != text:
                stale.append(os.path.relpath(path, ROOT))
        elif cur != text:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, 'w', encoding='utf-8', newline='\n') as f:
                f.write(text)
            print('wrote %s' % os.path.relpath(path, ROOT))
    if stale:
        print('stale (run py tools/gen_ui.py): %s' % ', '.join(stale), file=sys.stderr)
        return 1
    if '--check' in argv:
        print('the generated UI files are current and every state has a presentation')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
